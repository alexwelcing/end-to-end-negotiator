//! The generated specs, written by `nerve gen`: the interfaces whose rules repeat per item, card, car
//! or disc are produced by code so the repeated clauses stay identical, and so the counts in their
//! header comments are computed, not typed. The negotiation is generated for its `learn` examples:
//! one per state, computed from the policy they show. Each generator is one file here, returning the
//! spec text; `specs/<name>.nerve` is its output and must not be edited by hand (a test regenerates
//! every one and compares).

mod fifteen;
mod hanoi;
mod insert_remove;
mod kanban;
mod linked_sliders;
mod negotiate;
mod reorder;
mod rush_hour;
mod scheduler;
mod sokoban;
mod todo;

use anyhow::{bail, Result};
use std::path::Path;

/// Every generated spec, in alphabetical order.
pub const ALL: [&str; 11] = ["fifteen", "hanoi", "insert_remove", "kanban", "linked_sliders", "negotiate", "reorder", "rush_hour", "scheduler", "sokoban", "todo"];

/// The spec text of one generated interface.
pub fn generate(name: &str) -> Result<String> {
    Ok(match name {
        "fifteen" => fifteen::spec(),
        "hanoi" => hanoi::spec(),
        "insert_remove" => insert_remove::spec(),
        "kanban" => kanban::spec(),
        "linked_sliders" => linked_sliders::spec(),
        "negotiate" => negotiate::spec(),
        "reorder" => reorder::spec(),
        "rush_hour" => rush_hour::spec(),
        "scheduler" => scheduler::spec(),
        "sokoban" => sokoban::spec(),
        "todo" => todo::spec(),
        other => bail!("no generator for {other:?}; the generated specs are {}", ALL.join(", ")),
    })
}

/// Writes `<dir>/<name>.nerve` for each name (all of them when `names` is empty); returns what was written.
pub fn write(dir: &Path, names: &[String]) -> Result<Vec<String>> {
    let names: Vec<String> = if names.is_empty() { ALL.iter().map(|s| s.to_string()).collect() } else { names.to_vec() };
    let mut written = Vec::new();
    for n in &names {
        let text = generate(n)?;
        std::fs::create_dir_all(dir)?;
        std::fs::write(dir.join(format!("{n}.nerve")), text)?;
        written.push(n.clone());
    }
    Ok(written)
}

/// `1234567` -> `1,234,567`, as Python's `{n:,}`.
pub(crate) fn commas(n: usize) -> String {
    let s = n.to_string();
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

/// The standard header every generated spec ends its comment with.
pub(crate) fn generated_by(name: &str) -> String {
    format!("# Generated by `nerve gen {name}` (crates/nerve/src/gen/{name}.rs); edit the generator, not this file.")
}

/// Joins the lines of a spec into its text.
pub(crate) fn text(lines: Vec<String>) -> String {
    let mut s = lines.join("\n");
    s.push('\n');
    s
}

/// Shorthand for one line.
pub(crate) fn l(s: impl Into<String>) -> String {
    s.into()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_committed_specs_are_what_the_generators_write() {
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../specs");
        for name in ALL {
            let want = generate(name).unwrap();
            let have = std::fs::read_to_string(dir.join(format!("{name}.nerve"))).unwrap().replace("\r\n", "\n");
            assert!(have == want, "specs/{name}.nerve differs from `nerve gen {name}`: regenerate it");
        }
    }

    #[test]
    fn every_generated_spec_parses_and_checks() {
        for name in ALL {
            let sp = crate::spec::Spec::parse(&generate(name).unwrap()).unwrap_or_else(|e| panic!("{name}: {e:#}"));
            assert_eq!(sp.name, name);
            assert!(sp.scene.is_some(), "{name} has a scene");
            let problems = crate::oracle::Oracle::new(&sp).self_check(&mut rand::rngs::StdRng::seed_from_u64(0)).unwrap();
            assert!(problems.is_empty(), "{name}: {problems:?}");
        }
    }

    #[test]
    fn commas_group_thousands() {
        assert_eq!(commas(7776), "7,776");
        assert_eq!(commas(360), "360");
        assert_eq!(commas(1234567), "1,234,567");
    }

    use rand::SeedableRng;
}
