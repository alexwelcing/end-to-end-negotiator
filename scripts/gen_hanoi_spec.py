"""Write specs/hanoi.nerve (usage: python scripts/gen_hanoi_spec.py specs/hanoi.nerve).

Dragology's `hanoi` demo with four disks. The spec writes the rules (only a top disk moves, never onto a
smaller one), and a `learn` hole, `hint`, gives the optimal next move toward peg 2 only by example: one
example per position, found here by breadth-first search. A training run holds some of those examples out,
so the network is scored on positions whose solution it never saw.
"""
import sys
from collections import deque
from itertools import product
from pathlib import Path

DISKS = 4                      # d1 is the smallest
PEGS = 3
GOAL_PEG = 2
NONE = DISKS + 1               # "no disk on this peg" compares larger than every disk
F = [f"d{k}" for k in range(1, DISKS + 1)]


def top_expr(peg: str) -> str:
    """Smallest disk on `peg`, or NONE: the disk a move from `peg` would lift."""
    chain = " else ".join(f"{k} if {F[k - 1]} == {peg}" for k in range(1, DISKS + 1))
    return f"({chain} else {NONE})"


def top(state: tuple[int, ...], peg: int) -> int:
    return min((k for k in range(1, DISKS + 1) if state[k - 1] == peg), default=NONE)


def moves(state: tuple[int, ...]):
    for src, dst in product(range(PEGS), repeat=2):
        k = top(state, src)
        if src != dst and k < NONE and k < top(state, dst):
            nxt = list(state)
            nxt[k - 1] = dst
            yield tuple(nxt)


def solution() -> dict[tuple[int, ...], tuple[int, ...]]:
    """The optimal next position toward all disks on GOAL_PEG, for every position; unique for Hanoi."""
    goal = (GOAL_PEG,) * DISKS
    dist = {goal: 0}
    queue = deque([goal])
    while queue:
        s = queue.popleft()
        for n in moves(s):            # moves are reversible, so search outward from the goal
            if n not in dist:
                dist[n] = dist[s] + 1
                queue.append(n)
    assert len(dist) == PEGS ** DISKS, "every position reaches the goal"
    best = {goal: goal}
    for s, d in dist.items():
        if d:
            closer = [n for n in moves(s) if dist[n] == d - 1]
            assert len(closer) == 1, f"{s}: {len(closer)} optimal moves"
            best[s] = closer[0]
    return best


def legal_single_move() -> str:
    """At most one disk moved, and if one did it was on top before and lands on a larger disk or an empty peg."""
    moved = " + ".join(f"int({f} != old.{f})" for f in F)
    per_disk = []
    for k in range(1, DISKS + 1):
        f = F[k - 1]
        smaller = [F[j - 1] for j in range(1, k)]
        clear = " and ".join(f"old.{s} != old.{f} and old.{s} != {f}" for s in smaller) or "True"
        per_disk.append(f"({f} == old.{f} or ({clear}))")
    return f"({moved}) <= 1 and " + " and ".join(per_disk)


def stack_height(k: int) -> str:
    larger = [F[j - 1] for j in range(k + 1, DISKS + 1)]
    return " + ".join(f"int({g} == {F[k - 1]})" for g in larger) or "0"


def spec() -> str:
    best = solution()
    examples = "\n".join(
        "      - { state: {" + ", ".join(f"{f}: {v}" for f, v in zip(F, s)) + "}, next: {"
        + ", ".join(f"{f}: {v}" for f, v in zip(F, best[s])) + "} }"
        for s in sorted(best)
    )
    lines = [
        "# Dragology's Tower of Hanoi, four disks (d1 smallest). The rules are written down: only a top",
        "# disk moves, and never onto a smaller one, so a drag can only offer legal drops. `hint` is not:",
        "# it is the optimal next move toward peg 2, given only by example (one per position). Training",
        "# holds some examples out, and the network is scored on positions whose solution it never saw.",
        "# Generated by scripts/gen_hanoi_spec.py; edit the script, not this file.",
        "nerve: 1",
        "name: hanoi",
        "state:",
        *[f"  {f}: {{type: int, range: [0, {PEGS - 1}]}}   # peg of disk {k}" for k, f in enumerate(F, 1)],
        "actions:",
        f"  move: {{params: {{src: {{type: int, range: [0, {PEGS - 1}]}}, dst: {{type: int, range: [0, {PEGS - 1}]}}}}}}",
        "  hint: {}   # the optimal next move toward peg 2: shown by examples, never written down",
        "transitions:",
        "  move:",
        f"    when: \"{top_expr('src')} < {NONE} and {top_expr('src')} < {top_expr('dst')}\"",
        *[f"    {f}: \"dst if {top_expr('src')} == {k} else {f}\"" for k, f in enumerate(F, 1)],
        "ensures:",
        f"  - {{ after: move, holds: \"{legal_single_move()}\" }}",
        f"  - {{ after: hint, holds: \"{legal_single_move()}\" }}   # a hint may only make a legal move",
        "render:",
        *[f"  disk{k}: {{ x: \"70 + 140 * {f}\", y: \"200 - 30 * ({stack_height(k)})\" }}" for k, f in enumerate(F, 1)],
        "futures:",
        "  # one gesture per disk: only a top disk has anywhere to go, and only onto a larger disk",
        *[f"  drag_disk{k}: {{ kind: closest, over: {f}, grab: disk{k}, action: move, stickiness: 8, floating: true }}"
          for k, f in enumerate(F, 1)],
        "learn:",
        "  - name: solve",
        "    action: hint",
        f"    fallback: {{ {F[0]}: \"{F[0]}\" }}",
        "    examples:",
        examples,
        "initial: {" + ", ".join(f"{f}: 0" for f in F) + "}",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(spec(), encoding="utf-8")
    print(f"wrote {sys.argv[1]}: {PEGS ** DISKS} positions, optimal moves unique")
