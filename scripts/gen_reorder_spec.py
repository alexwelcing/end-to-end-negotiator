"""Write specs/reorder.nerve (usage: python scripts/gen_reorder_spec.py specs/reorder.nerve): Dragology's reorderable list, five items, as position fields.

The spec language has no `list<T>` yet (ROADMAP 7), so a list is one position per item
plus an all-distinct invariant; `move(item, to)` takes the item out and shifts the
items in between by one, exactly `moveItem(items, i, j)` in Dragology's demo.
"""
import sys
from itertools import combinations
from pathlib import Path

ITEMS = "abcde"
N = len(ITEMS)
P = {x: f"p{x}" for x in ITEMS}
FROM = " else ".join(f"{P[x]} if item == '{x}'" for x in ITEMS[:-1]) + f" else {P[ITEMS[-1]]}"


def update(x: str) -> str:
    p = P[x]
    return (f"to if item == '{x}' else ({p} - 1 if ({FROM}) < {p} <= to "
            f"else ({p} + 1 if to <= {p} < ({FROM}) else {p}))")


lines = [
    "# Dragology's reorderable list: five items, drag one to a new place and the others make room.",
    "# There is no list type yet (ROADMAP 7), so the list is one position per item and an invariant",
    "# that no two share a place. `move` is Dragology's moveItem(items, i, j): the drag's futures are",
    "# every order one move away, derived from this rule instead of written out by hand.",
    "# Generated by scripts/gen_reorder_spec.py so the five shift rules stay identical; edit the script, not this file.",
    "nerve: 1",
    "name: reorder",
    "state:",
    *[f"  {P[x]}: {{type: int, range: [0, {N - 1}]}}   # position of item {x}" for x in ITEMS],
    "actions:",
    f"  move: {{params: {{item: {{type: enum, values: [{', '.join(ITEMS)}]}}, to: {{type: int, range: [0, {N - 1}]}}}}}}",
    "transitions:",
    "  move:",
    *[f"    {P[x]}: \"{update(x)}\"" for x in ITEMS],
    "invariants:",
    "  - \"" + " and ".join(f"{P[x]} != {P[y]}" for x, y in combinations(ITEMS, 2)) + "\"",
    "ensures:",
    f"  - {{ after: move, holds: \"({FROM}) == to\" }}   # the moved item lands where it was dropped",
    "render:",
    *[f"  {x}: {{ x: \"40 + 64 * {P[x]}\", y: 40 }}" for x in ITEMS],
    "futures:",
    "  # one gesture per item: grab it, and every order one move away competes for the pointer",
    *[f"  drag_{x}: {{ kind: closest, over: {P[x]}, grab: {x}, action: move, stickiness: 6, floating: true }}" for x in ITEMS],
    "initial: {" + ", ".join(f"{P[x]}: {i}" for i, x in enumerate(ITEMS)) + "}",
]
Path(sys.argv[1]).write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
