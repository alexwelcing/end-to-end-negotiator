"""Write specs/insert_remove.nerve (usage: python scripts/gen_insert_remove_spec.py specs/insert_remove.nerve).

Dragology's `insert-and-remove` demo: a list of fruit tiles under a toolbar. Dragging a list tile lifts it out
and offers every insert position in the rest of the list, or the trash (it is removed); dragging a toolbar
tile offers every insert position in the list, or the trash (nothing is added). Far from all of those, the drag
falls back to the state it started in (`whenFar`, 50 px by default).

Scaled down: Dragology's list is unbounded and the toolbar mints a fresh tile per pull. Here there are four
tiles with fixed identities: a and b are apples and c a banana (Dragology's starting list), d is grapes. Each
tile's field is its list index, or OUT: off the list, drawn in its own toolbar slot. A tile's toolbar slot is
both Dragology's store (pull it from there into the list) and its trash (drop it there to remove it), so the
store holds only the tiles not in the list. The list is one index per tile plus invariants (no list type yet).

`move_<tile>(to)` is the drop: lift the tile out (the tiles after it close the gap), then insert it at index
`to` (the tiles from there on make room), or leave it out when `to == OUT`. Each tile has its own action, so
dragging one tile can only move that tile.
"""
import sys
from itertools import permutations
from pathlib import Path

TILES = "abcd"
LABELS = {"a": "apple", "b": "apple", "c": "banana", "d": "grapes"}
START = "abc"                      # Dragology's initial list: apple, apple, banana
OUT = len(TILES)                   # field value for "not in the list"
P = {t: f"p{t}" for t in TILES}
TILE_PX = 50                       # Dragology's TILE_SIZE
X0, TOOLBAR_Y, LIST_Y = 30, 30, 110
FAR = 50                           # Dragology's whenFar default gap


def in_list_count(skip: str | None = None) -> str:
    """How many tiles (other than `skip`) are in the list."""
    return "(" + " + ".join(f"int({P[t]} < {OUT})" for t in TILES if t != skip) + ")"


def update(moved: str, x: str) -> str:
    """Index of tile `x` after `move_<moved>(to)`: close the gap `moved` leaves, then make room at `to`."""
    if x == moved:
        return "to"
    closed = f"({P[x]} - 1 if {P[moved]} < {P[x]} < {OUT} else {P[x]})"
    return f"{closed} + 1 if to <= {closed} < {OUT} else {closed}"


def others_unchanged(moved: str) -> str:
    """The other tiles stay in (or out of) the list, and those in it keep their order."""
    rest = [t for t in TILES if t != moved]
    member = [f"({P[t]} == {OUT}) == (old.{P[t]} == {OUT})" for t in rest]
    order = [
        f"(old.{P[x]} == {OUT} or old.{P[y]} == {OUT} or ({P[x]} < {P[y]}) == (old.{P[x]} < old.{P[y]}))"
        for i, x in enumerate(rest) for y in rest[i + 1:]
    ]
    return " and ".join(member + order)


def counts() -> tuple[int, int]:
    boards = sum(1 for n in range(len(TILES) + 1) for _ in permutations(TILES, n))
    return (OUT + 1) ** len(TILES), boards


def spec() -> str:
    tuples, boards = counts()
    pairs = [(x, y) for i, x in enumerate(TILES) for y in TILES[i + 1:]]
    distinct = " and ".join(f"({P[x]} == {OUT} or {P[x]} != {P[y]})" for x, y in pairs)
    packed = " and ".join(f"({P[t]} == {OUT} or {P[t]} < {in_list_count()})" for t in TILES)
    initial = {t: (START.index(t) if t in START else OUT) for t in TILES}
    lines = [
        "# Dragology's insert-and-remove: fruit tiles in a list under a toolbar. Drag a tile to any place",
        "# in the list (the rest make room) or to the trash; pull one from the toolbar into any place, or",
        "# let it go back. Far from every option (whenFar, 50 px) the drag falls back to where it began.",
        "# Scaled down: four tiles with fixed identities instead of an unbounded list and a toolbar that",
        "# mints new ones. a, b = apple and c = banana (Dragology's starting list), d = grapes. A tile's",
        f"# field is its list index, or {OUT} = out of the list, drawn in its own toolbar slot: that slot is both",
        "# Dragology's store (pull from it) and its trash (drop on it). The invariants say the tiles in the",
        f"# list are packed from index 0 with none sharing one, so {boards} of the {tuples} index tuples are",
        "# lists. `move_<tile>(to)` lifts the tile out (the ones after it close up) and inserts it at `to`.",
        "# Generated by scripts/gen_insert_remove_spec.py; edit the script, not this file.",
        "nerve: 1",
        "name: insert_remove",
        "state:",
        *[f"  {P[t]}: {{type: int, range: [0, {OUT}]}}   # list index of tile {t} ({LABELS[t]}); {OUT} = in the toolbar"
          for t in TILES],
        "actions:",
        *[f"  move_{t}: {{params: {{to: {{type: int, range: [0, {OUT}]}}}}}}   # drop {t} at list index `to`, or {OUT}: remove it"
          for t in TILES],
        "transitions:",
        *[
            line
            for t in TILES
            for line in [
                f"  move_{t}:",
                # an insert index may be at most the length of the list without this tile
                f"    when: \"to == {OUT} or to <= {in_list_count(skip=t)}\"",
                *[f"    {P[x]}: \"{update(t, x)}\"" for x in TILES],
            ]
        ],
        "invariants:",
        f"  - \"{distinct}\"   # no two tiles share an index",
        f"  - \"{packed}\"   # the list is packed from index 0",
        "ensures:",
        *[f"  - {{ after: move_{t}, holds: \"{P[t]} == to or {P[t]} == old.{P[t]}\" }}   # the tile lands where it was dropped, or stays"
          for t in TILES],
        *[f"  - {{ after: move_{t}, holds: \"{others_unchanged(t)}\" }}   # nothing else joins or leaves, and the rest keep their order"
          for t in TILES],
        "render:",
        *[f"  {t}: {{ x: \"{X0} + {TILE_PX} * ({k} if {P[t]} == {OUT} else {P[t]})\", y: \"{TOOLBAR_Y} if {P[t]} == {OUT} else {LIST_Y}\" }}"
          for k, t in enumerate(TILES)],
        "futures:",
        "  # one gesture per tile: every list index it can be dropped at, or its toolbar slot (out)",
        *[f"  drag_{t}: {{ kind: closest, over: {P[t]}, grab: {t}, action: move_{t}, stickiness: 6, far: {FAR}, floating: true }}"
          for t in TILES],
        "initial: {" + ", ".join(f"{P[t]}: {initial[t]}" for t in TILES) + "}",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(spec(), encoding="utf-8")
    t, b = counts()
    print(f"wrote {sys.argv[1]}: {t} tuples, {b} lists")
