"""Write specs/scheduler.nerve (usage: python scripts/gen_scheduler_spec.py specs/scheduler.nerve).

Dragology's `scheduler` demo (src/demos/scheduler.tsx): meetings on a timeline, one track per room. Each meeting is
a bar with a dot at each end. Dragging the bar moves the meeting to any room (`d.between` over every room); dragging
a dot moves that end alone (`d.vary` on `start` or `end` under `lessThan(0, start)`, `lessThan(start, end -
MIN_LENGTH)`, `lessThan(end, END_TIME)`). Overlaps are allowed: Dragology draws the overlap graph and marks a
double-booked room in red, it never forbids one.

Scaled down so every tuple can be enumerated: 3 meetings (of 5), 2 rooms (of 4), and a timeline of 3 whole slots
(of 250 px) with a one-slot minimum length. Per meeting 2 * 3 * 3 = 18 tuples, 12 of them meetings, so 1,728 of the
5,832 tuples are schedules. On the slot grid `vary` becomes `closest` over the end's slot: every slot the
constraints allow is a future, and a pointer past a limit stops at it.
"""
import sys
from pathlib import Path

MEETINGS = 3
ROOMS = 2
SLOTS = 3                      # the timeline runs 0..SLOTS in whole slots (Dragology's END_TIME)
MIN_LEN = 1                    # Dragology's MIN_LENGTH, in slots
# (room, start, end): Dragology's first three meetings overlap in a chain without a double booking; so do these.
INITIAL = [(0, 0, 2), (1, 1, 3), (1, 0, 1)]
X0, SLOT_W = 60, 100           # x of slot t is X0 + SLOT_W * t
Y0, ROOM_H, ROW_H = 40, 170, 48  # each room is a band; each meeting has its own row in it, so handles never coincide


def fields(i: int) -> list[str]:
    return [f"room{i}", f"start{i}", f"end{i}"]


def unchanged(names: list[str]) -> str:
    return " and ".join(f"{f} == old.{f}" for f in names)


def others(i: int) -> list[str]:
    return [f for j in range(MEETINGS) if j != i for f in fields(j)]


def row_y(i: int) -> str:
    return f"{Y0 + ROW_H * i} + {ROOM_H} * room{i}"


def spec() -> str:
    lines = [
        "# Dragology's meeting scheduler (src/demos/scheduler.tsx): meetings as bars on a timeline, one track per room.",
        "# The rule: drag a bar to move its meeting to any room; drag the dot at either end to move that end alone,",
        "# never off the timeline and never closer than MIN_LENGTH to the other end. Meetings may overlap, even in",
        "# one room: Dragology draws the overlap graph and marks a double booking in red, it never forbids one (the",
        "# graph is not drawn here, render has points only). Scaled down: 3 meetings (of 5), 2 rooms (of 4), a",
        "# 3-slot timeline (of 250 px) with ends on whole slots and a one-slot minimum, so 1,728 of the 5,832 tuples",
        "# are schedules. On the grid an end's `vary` becomes `closest` over its slot; the bar's drag is `between`.",
        "# Each meeting has its own row inside a room's band so that no two handles ever coincide.",
        "# Generated by scripts/gen_scheduler_spec.py; edit the script, not this file.",
        "nerve: 1",
        "name: scheduler",
        "state:",
        *[
            line
            for i in range(MEETINGS)
            for line in [
                f"  room{i}: {{type: int, range: [0, {ROOMS - 1}]}}   # meeting {i}'s room",
                f"  start{i}: {{type: int, range: [0, {SLOTS - MIN_LEN}]}}   # meeting {i} starts at this slot",
                f"  end{i}: {{type: int, range: [{MIN_LEN}, {SLOTS}]}}   # ... and ends at this one",
            ]
        ],
        "actions:",
        *[
            line
            for i in range(MEETINGS)
            for line in [
                f"  set_room{i}: {{params: {{to: {{type: int, range: [0, {ROOMS - 1}]}}}}}}   # drag meeting {i}'s bar",
                f"  set_start{i}: {{params: {{to: {{type: int, range: [0, {SLOTS - MIN_LEN}]}}}}}}   # drag its left dot",
                f"  set_end{i}: {{params: {{to: {{type: int, range: [{MIN_LEN}, {SLOTS}]}}}}}}   # drag its right dot",
            ]
        ],
        "transitions:",
        *[
            line
            for i in range(MEETINGS)
            for line in [
                f"  set_room{i}: {{ room{i}: \"to\" }}",
                f"  set_start{i}: {{ when: \"to + {MIN_LEN} <= end{i}\", start{i}: \"to\" }}",
                f"  set_end{i}: {{ when: \"start{i} + {MIN_LEN} <= to\", end{i}: \"to\" }}",
            ]
        ],
        "invariants:",
        "  # Dragology's vary constraints: lessThan(0, start), lessThan(start, end - MIN_LENGTH), lessThan(end, END_TIME)",
        *[f"  - \"0 <= start{i} and start{i} + {MIN_LEN} <= end{i} <= {SLOTS}\"" for i in range(MEETINGS)],
        "ensures:",
        *[
            line
            for i in range(MEETINGS)
            for line in [
                f"  - {{ after: set_room{i}, holds: \"room{i} == to and {unchanged([f'start{i}', f'end{i}'] + others(i))}\" }}"
                "   # the meeting changes room, keeps its time, and no other meeting moves",
                f"  - {{ after: set_start{i}, holds: \"(start{i} == to or start{i} == old.start{i}) and "
                f"{unchanged([f'room{i}', f'end{i}'] + others(i))}\" }}   # only that end moves",
                f"  - {{ after: set_end{i}, holds: \"(end{i} == to or end{i} == old.end{i}) and "
                f"{unchanged([f'room{i}', f'start{i}'] + others(i))}\" }}   # only that end moves",
            ]
        ],
        "render:",
        *[
            line
            for i in range(MEETINGS)
            for line in [
                f"  bar{i}: {{ x: \"{X0} + {SLOT_W // 2} * (start{i} + end{i})\", y: \"{row_y(i)}\" }}   # middle of the bar",
                f"  left{i}: {{ x: \"{X0} + {SLOT_W} * start{i}\", y: \"{row_y(i)}\" }}",
                f"  right{i}: {{ x: \"{X0} + {SLOT_W} * end{i}\", y: \"{row_y(i)}\" }}",
            ]
        ],
        "futures:",
        "  # per meeting: the bar goes to any room (Dragology `between`, no snap radius here); each dot to every slot",
        "  # its end may take (Dragology `vary` with constraints, on the slot grid)",
        *[
            line
            for i in range(MEETINGS)
            for line in [
                f"  drag_bar{i}: {{ kind: between, over: room{i}, grab: bar{i}, action: set_room{i} }}",
                f"  drag_left{i}: {{ kind: closest, over: start{i}, grab: left{i}, action: set_start{i}, stickiness: 6 }}",
                f"  drag_right{i}: {{ kind: closest, over: end{i}, grab: right{i}, action: set_end{i}, stickiness: 6 }}",
            ]
        ],
        "initial: {" + ", ".join(
            f"room{i}: {r}, start{i}: {s}, end{i}: {e}" for i, (r, s, e) in enumerate(INITIAL)
        ) + "}",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(spec(), encoding="utf-8")
    print(f"wrote {sys.argv[1]}")
