"""Write specs/linked_sliders.nerve (usage: python scripts/gen_linked_sliders_spec.py specs/linked_sliders.nerve).

Dragology's `linked-sliders` demo: a stack of sliders on tracks of width W. Dragging slider i shifts it and
every slider below it by the same delta (`d.varyFunc([0], ([delta]) => values[j] += delta for j >= i)`),
under the constraint that every value stays on its track (`inOrder([0, v, W])`). So the group moves rigidly
and stops as soon as any member reaches an end of its track.

`set_<i>(to)` asks for slider i at `to`; the delta is `to - v_i` clamped to what keeps the whole group on the
tracks, `[-min(group), W - max(group)]`, and every slider in the group moves by it. The outer `clamp(.., 0, W)`
on each update is a no-op in exact arithmetic and only keeps float rounding inside the field's range.
Dragology has five sliders; this has three (the continuous trainer descends over all three fields at once).
"""
import sys
from pathlib import Path

N = 3          # sliders (Dragology: 5)
W = 240        # track width, as Dragology's W
X0 = 40        # Dragology's X0: where a track starts
Y0 = 30        # Dragology's Y0
SPACING = 40   # Dragology's SPACING is 36; 40 keeps the lab's circles apart
TOL = "0.001"  # float slack for "slider i reached `to`" and "the group kept its shape"
V = [f"v{i}" for i in range(1, N + 1)]


def group(i: int) -> list[str]:
    """Slider i (0-based) and every slider below it: the ones a drag of slider i moves."""
    return V[i:]


def lowest(names: list[str]) -> str:
    return names[0] if len(names) == 1 else f"min({', '.join(names)})"


def highest(names: list[str]) -> str:
    return names[0] if len(names) == 1 else f"max({', '.join(names)})"


def delta(i: int) -> str:
    """Dragology's delta for slider i: as far towards `to` as the group can go and stay on the tracks."""
    g = group(i)
    return f"clamp(to - {V[i]}, -{lowest(g)}, {W} - {highest(g)})"


def ensures(i: int) -> list[str]:
    g, vi = group(i), V[i]
    out = []
    if i > 0:
        still = " and ".join(f"{v} == old.{v}" for v in V[:i])
        out.append(f"  - {{ after: set_{i + 1}, holds: \"{still}\" }}   # the sliders above do not move")
    for v in g[1:]:
        out.append(f"  - {{ after: set_{i + 1}, holds: \"abs(({v} - {vi}) - (old.{v} - old.{vi})) < {TOL}\" }}"
                   f"   # {v} moves with {vi}")
    reached = (f"abs({vi} - to) < {TOL} or (to > old.{vi} and {highest(g)} == {W})"
               f" or (to < old.{vi} and {lowest(g)} == 0)")
    out.append(f"  - {{ after: set_{i + 1}, holds: \"{reached}\" }}   # it reaches `to`, or the group is at an end")
    return out


def spec() -> str:
    on_tracks = " and ".join(f"0 <= {v} <= {W}" for v in V)
    initial = ", ".join(f"{v}: {(i + 1) / (N + 1) * W}" for i, v in enumerate(V))
    lines = [
        "# Dragology's linked-sliders (src/demos/linked-sliders.tsx): a stack of sliders on tracks.",
        "# Rule: dragging slider i moves it and every slider below it by the same amount, and the whole group",
        "# stops as soon as any of them reaches an end of its track (`d.varyFunc` with an `inOrder([0, v, W])`",
        "# constraint on every value). Scaled down from five sliders to three; vertical spacing 36 -> 40 px.",
        "# `set_<i>(to)` asks for slider i at `to` and moves the group by `to - v_i`, clamped to keep it on the tracks.",
        "# Generated by scripts/gen_linked_sliders_spec.py; edit the script, not this file.",
        "nerve: 1",
        "name: linked_sliders",
        "state:",
        *[f"  {v}: {{type: float, range: [0, {W}]}}   # slider {i + 1}" for i, v in enumerate(V)],
        "actions:",
        *[f"  set_{i + 1}: {{params: {{to: {{type: float, range: [0, {W}]}}}}}}" for i in range(N)],
        "transitions:",
        *[
            line
            for i in range(N)
            for line in [f"  set_{i + 1}:", *[f"    {v}: \"clamp({v} + {delta(i)}, 0, {W})\"" for v in group(i)]]
        ],
        "invariants:",
        f"  - \"{on_tracks}\"",
        "ensures:",
        *[line for i in range(N) for line in ensures(i)],
        "render:",
        *[f"  thumb{i + 1}: {{ x: \"{X0} + {v}\", y: {Y0 + i * SPACING} }}" for i, v in enumerate(V)],
        "futures:",
        "  # one vary per thumb, realised through its own set_<i> so the group moves and the clamp applies",
        *[f"  drag_{i + 1}: {{ kind: vary, over: {v}, grab: thumb{i + 1}, action: set_{i + 1}, param: to }}"
          for i, v in enumerate(V)],
        # Dragology's initial state: values[i] = (i + 1) / (N + 1) * W
        f"initial: {{{initial}}}",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__.splitlines()[0])
    Path(sys.argv[1]).write_text(spec(), encoding="utf-8")
    print(f"wrote {sys.argv[1]}")
