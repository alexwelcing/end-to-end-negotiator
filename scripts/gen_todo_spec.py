"""Write specs/todo.nerve (usage: python scripts/gen_todo_spec.py specs/todo.nerve).

Dragology's `todo` demo (src/demos/todo.tsx): a list of cards, each with a `completed` checkbox. Dragging a card
splices it out and back in at any index (`statesWith`); ticking the box flips that card's `completed` and nothing
else. The text box and the Add button need a text type, so cards are not added, typed or renamed here.

There is no list type yet (ROADMAP 7), so the list is one position per card plus "no two share a place", and one
done flag per card: 4! orders x 2^4 completions = 384 of the 4^4 * 2^4 = 4,096 tuples are lists. Each card has its
own `move_<card>(to)` (so dragging a card moves that card) and its own `toggle_<card>` (the checkbox).
"""
import sys
from itertools import combinations
from pathlib import Path

ITEMS = "abcd"                 # Dragology starts with a, b, c; d stands in for one card added with the Add box
N = len(ITEMS)
DONE = "b"                     # Dragology's initial list: b ("Walk the dog") is the completed one
P = {x: f"p{x}" for x in ITEMS}
D = {x: f"d{x}" for x in ITEMS}
TOP, ROW = 60, 55              # Dragology's TILE_SIZE is 55
LEFT, INDENT = 60, 50          # a completed card is drawn INDENT px to the right (Dragology strikes it through)


def update(card: str, x: str) -> str:
    """Position of `x` after `move_<card>(to)`: splice `card` out, then back in at `to`."""
    if x == card:
        return "to"
    frm, p = P[card], P[x]
    return f"{p} - 1 if {frm} < {p} <= to else ({p} + 1 if to <= {p} < {frm} else {p})"


def unchanged(fields: list[str]) -> str:
    return " and ".join(f"{f} == old.{f}" for f in fields)


def spec() -> str:
    distinct = " and ".join(f"{P[x]} != {P[y]}" for x, y in combinations(ITEMS, 2))
    lines = [
        "# Dragology's todo list (src/demos/todo.tsx): drag a card to reorder the list, tick its box to complete it.",
        "# The rule: a drag lifts the card out and splices it back in at any index (the cards in between close up",
        "# and make room), and a tick flips that card's `completed` and nothing else. Scaled down: four cards with",
        "# no text. Dragology's text box and Add button need a text type, so cards are not added, typed or renamed;",
        "# Dragology starts with a, b (completed), c, and d stands in for one more card. With no list type",
        "# (ROADMAP 7) a card's place is a position field, so 384 of the 4,096 tuples are lists (24 orders x 16",
        "# completions). The drag is Dragology's `useFloating` variant, closest + floating; its `whenFar(stateWithout)`",
        "# (the list without the card) is not a state here. A completed card is drawn 50 px to the right.",
        "# Generated by scripts/gen_todo_spec.py; edit the script, not this file.",
        "nerve: 1",
        "name: todo",
        "state:",
        *[f"  {P[x]}: {{type: int, range: [0, {N - 1}]}}   # position of card {x}, top to bottom" for x in ITEMS],
        *[f"  {D[x]}: {{type: bool}}   # card {x} is completed" for x in ITEMS],
        "actions:",
        *[f"  move_{x}: {{params: {{to: {{type: int, range: [0, {N - 1}]}}}}}}   # drag card {x} to index `to`" for x in ITEMS],
        *[f"  toggle_{x}: {{}}   # tick card {x}'s checkbox" for x in ITEMS],
        "transitions:",
        *[
            line
            for x in ITEMS
            for line in [f"  move_{x}:", *[f"    {P[y]}: \"{update(x, y)}\"" for y in ITEMS]]
        ],
        *[f"  toggle_{x}: {{ {D[x]}: \"not {D[x]}\" }}" for x in ITEMS],
        "invariants:",
        f"  - \"{distinct}\"",
        "ensures:",
        *[f"  - {{ after: move_{x}, holds: \"{P[x]} == to and {unchanged([D[y] for y in ITEMS])}\" }}"
          "   # the card lands where it was dropped, and a drag completes nothing"
          for x in ITEMS],
        *[f"  - {{ after: toggle_{x}, holds: \"{D[x]} != old.{D[x]} and "
          f"{unchanged([D[y] for y in ITEMS if y != x] + [P[y] for y in ITEMS])}\" }}"
          "   # a tick completes (or reopens) that card only, and never reorders"
          for x in ITEMS],
        "render:",
        *[f"  {x}: {{ x: \"{LEFT} + {INDENT} * int({D[x]})\", y: \"{TOP} + {ROW} * {P[x]}\" }}" for x in ITEMS],
        "futures:",
        "  # one gesture per card: every index it can be spliced back in at (Dragology's `statesWith`)",
        *[f"  drag_{x}: {{ kind: closest, over: {P[x]}, grab: {x}, action: move_{x}, stickiness: 6, floating: true }}"
          for x in ITEMS],
        "initial: {" + ", ".join([f"{P[x]}: {i}" for i, x in enumerate(ITEMS)]
                                 + [f"{D[x]}: {'true' if x in DONE else 'false'}" for x in ITEMS]) + "}",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(spec(), encoding="utf-8")
    print(f"wrote {sys.argv[1]}")
