"""Write specs/kanban.nerve (usage: python scripts/gen_kanban_spec.py specs/kanban.nerve).

Dragology's `kanban` demo: four cards in three columns (to do, doing, done). There is no list type yet
(ROADMAP 7), so each card has one slot, column * 4 + position, and invariants say no two cards share a
slot and every column is packed from the top. Of the 12^4 = 20,736 slot tuples, 360 are boards.

`move_<card>(to)` takes the card out of its column (the cards below it close the gap) and inserts it at
slot `to` (the cards at and below that position make room): a drag between or within columns. Each card
has its own action so that dragging a card means moving that card, not moving another one out of its way.
"""
import sys
from pathlib import Path

CARDS = "abcd"
COLS = 3
DEPTH = 4                          # slots per column; four cards always fit in one column
SLOTS = COLS * DEPTH
S = {c: f"s{c}" for c in CARDS}


def count_in_column(col: str, skip: str | None = None) -> str:
    """How many cards (other than `skip`) sit in column `col`."""
    terms = [f"int({S[c]} // {DEPTH} == {col})" for c in CARDS if c != skip]
    return "(" + " + ".join(terms) + ")"


def update(card: str, x: str) -> str:
    """Slot of card `x` after `move_<card>(to)`: close the gap, then make room."""
    if x == card:
        return "to"
    frm, sx = S[card], S[x]
    closed = f"({sx} - 1 if {sx} // {DEPTH} == {frm} // {DEPTH} and {sx} > {frm} else {sx})"
    return f"{closed} + 1 if {closed} // {DEPTH} == to // {DEPTH} and {closed} >= to else {closed}"


def spec() -> str:
    pairs = [(x, y) for i, x in enumerate(CARDS) for y in CARDS[i + 1:]]
    distinct = " and ".join(f"{S[x]} != {S[y]}" for x, y in pairs)
    packed = " and ".join(f"{S[x]} % {DEPTH} < {count_in_column(f'{S[x]} // {DEPTH}')}" for x in CARDS)
    lines = [
        "# Dragology's kanban board: four cards in three columns (to do, doing, done). A card's slot is",
        "# column * 4 + position. The invariants say no two cards share a slot and every column is packed",
        "# from the top, so 360 of the 20,736 slot tuples are boards. `move_<card>(to)` lifts the card out",
        "# (the cards below close the gap) and drops it at `to` (the cards there make room).",
        "# Generated by scripts/gen_kanban_spec.py; edit the script, not this file.",
        "nerve: 1",
        "name: kanban",
        "state:",
        *[f"  {S[c]}: {{type: int, range: [0, {SLOTS - 1}]}}   # slot of card {c}" for c in CARDS],
        "actions:",
        *[f"  move_{c}: {{params: {{to: {{type: int, range: [0, {SLOTS - 1}]}}}}}}" for c in CARDS],
        "transitions:",
        *[
            line
            for c in CARDS
            for line in [
                f"  move_{c}:",
                # the drop position may be at most one past the other cards already in that column
                f"    when: \"to % {DEPTH} <= {count_in_column(f'to // {DEPTH}', skip=c)}\"",
                *[f"    {S[x]}: \"{update(c, x)}\"" for x in CARDS],
            ]
        ],
        "invariants:",
        f"  - \"{distinct}\"",
        f"  - \"{packed}\"",
        "ensures:",
        *[f"  - {{ after: move_{c}, holds: \"{S[c]} == to or {S[c]} == old.{S[c]}\" }}   # the card lands where it was dropped, or stays"
          for c in CARDS],
        "render:",
        *[f"  {c}: {{ x: \"60 + 150 * ({S[c]} // {DEPTH})\", y: \"50 + 46 * ({S[c]} % {DEPTH})\" }}" for c in CARDS],
        "futures:",
        "  # one gesture per card: every slot it can be dropped into, in any column",
        *[f"  drag_{c}: {{ kind: closest, over: {S[c]}, grab: {c}, action: move_{c}, stickiness: 6, floating: true }}"
          for c in CARDS],
        # a, b in "to do"; c in "doing"; d in "done"
        "initial: {sa: 0, sb: 1, sc: 4, sd: 8}",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(spec(), encoding="utf-8")
    print(f"wrote {sys.argv[1]}")
